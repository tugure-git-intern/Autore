use std::fmt;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TechStack {
    Python,
    NodeJs,
    Java,
    Go,
}

impl TechStack {
    pub fn all() -> Vec<TechStack> {
        vec![
            TechStack::Python,
            TechStack::NodeJs,
            TechStack::Java,
            TechStack::Go,
        ]
    }

    pub fn from_str_loose(s: &str) -> Option<TechStack> {
        match s.trim().to_lowercase().as_str() {
            "python" | "py" => Some(TechStack::Python),
            "nodejs" | "node" | "js" | "javascript" => Some(TechStack::NodeJs),
            "java" | "spring" | "maven" => Some(TechStack::Java),
            "go" | "golang" => Some(TechStack::Go),
            _ => None,
        }
    }

    pub fn default_port(&self) -> u16 {
        match self {
            TechStack::Python => 8000,
            TechStack::NodeJs => 3000,
            TechStack::Java => 8080,
            TechStack::Go => 8080,
        }
    }
}

impl fmt::Display for TechStack {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            TechStack::Python => write!(f, "Python (3.12-slim)"),
            TechStack::NodeJs => write!(f, "Node.js (20-alpine)"),
            TechStack::Java => write!(f, "Java (Eclipse Temurin 21)"),
            TechStack::Go => write!(f, "Go (1.22-alpine multi-stage)"),
        }
    }
}

#[derive(Debug, Clone)]
pub struct InitConfig {
    pub app_name: String,
    pub stack: TechStack,
    pub app_port: u16,
    pub deploy_port: u16,
}

pub fn render_dockerfile(cfg: &InitConfig) -> String {
    match cfg.stack {
        TechStack::Python => format!(
            r#"# Generated by Autore CLI — Multi-stage Python Dockerfile
FROM python:3.12-slim AS test
WORKDIR /app
COPY . .
RUN if [ -f requirements.txt ]; then pip install --no-cache-dir -r requirements.txt; fi
RUN python -m unittest discover -v

FROM python:3.12-slim
WORKDIR /app
COPY --from=test /app /app
RUN useradd --system --no-create-home appuser
USER appuser
EXPOSE {port}
CMD ["python", "app.py"]
"#,
            port = cfg.app_port
        ),
        TechStack::NodeJs => format!(
            r#"# Generated by Autore CLI — Multi-stage Node.js Dockerfile
FROM node:20-alpine AS test
WORKDIR /app
COPY package*.json ./
RUN npm ci
COPY . .
RUN npm test --if-present

FROM node:20-alpine
WORKDIR /app
COPY --from=test /app /app
USER node
EXPOSE {port}
CMD ["node", "index.js"]
"#,
            port = cfg.app_port
        ),
        TechStack::Java => format!(
            r#"# Generated by Autore CLI — Multi-stage Java 21 Dockerfile
FROM maven:3.9-eclipse-temurin-21 AS build
WORKDIR /app
COPY pom.xml .
COPY src ./src
RUN mvn -B test package

FROM eclipse-temurin:21-jre-jammy
WORKDIR /app
COPY --from=build /app/target/*.jar /app/app.jar
RUN useradd --system --no-create-home appuser
USER appuser
EXPOSE {port}
ENTRYPOINT ["java", "-jar", "/app/app.jar"]
"#,
            port = cfg.app_port
        ),
        TechStack::Go => format!(
            r#"# Generated by Autore CLI — Multi-stage Go Dockerfile
FROM golang:1.22-alpine AS build
WORKDIR /src
COPY . .
RUN go test ./...
RUN CGO_ENABLED=0 go build -o /out/app .

FROM alpine:3.20
WORKDIR /app
COPY --from=build /out/app /app/app
RUN adduser -D -H appuser
USER appuser
EXPOSE {port}
ENTRYPOINT ["/app/app"]
"#,
            port = cfg.app_port
        ),
    }
}

pub fn render_jenkinsfile(cfg: &InitConfig) -> String {
    format!(
        r#"// Generated by Autore CLI — Standard DevSecOps Pipeline for {app_name}
pipeline {{
    agent {{ label 'docker' }}

    options {{
        buildDiscarder(logRotator(numToKeepStr: '20'))
        disableConcurrentBuilds()
    }}

    triggers {{
        pollSCM('* * * * *')
    }}

    environment {{
        APP_NAME    = '{app_name}'
        APP_DIR     = '.'
        APP_PORT    = '{app_port}'
        DEPLOY_PORT = '{deploy_port}'
    }}

    stages {{
        stage('Audit Info') {{
            steps {{
                script {{
                    env.FAILED_STAGE  = 'Audit Info'
                    env.SHORT_SHA     = sh(script: 'git rev-parse --short=7 HEAD', returnStdout: true).trim()
                    env.IMAGE_TAG     = "build-${{env.BUILD_NUMBER}}-commit-${{env.SHORT_SHA}}"
                    env.AUDIT_AUTHOR  = sh(script: "git log -1 --pretty='%an <%ae>'", returnStdout: true).trim()
                    env.AUDIT_MESSAGE = sh(script: 'git log -1 --pretty=%s', returnStdout: true).trim()
                    env.AUDIT_CAUSES  = currentBuild.getBuildCauses().collect {{ it.shortDescription }}.join(', ')
                    echo "Building ${{env.APP_NAME}}:${{env.IMAGE_TAG}} by ${{env.AUDIT_AUTHOR}} on ${{env.NODE_NAME}}"
                }}
            }}
        }}

        stage('Security Gate') {{
            steps {{
                script {{
                    env.FAILED_STAGE = 'Security Gate (Secret & Code Scan)'
                }}
                sh '''
                    # Authoritative scanner = admin-installed, root-owned binary only.
                    # No PATH lookup and no repo-provided script (repo is untrusted).
                    if [ -x /usr/local/bin/autore ] && [ "$(stat -c %u /usr/local/bin/autore)" = "0" ]; then
                        /usr/local/bin/autore scan --path "$APP_DIR"
                    else
                        echo "🚫 [SECURITY GATE ERROR] Scanner trusted /usr/local/bin/autore (root-owned) tidak ditemukan di runner!" >&2
                        echo "Build DIBATALKAN demi keamanan (Fail-Closed / Default-Deny)." >&2
                        exit 1
                    fi
                '''
            }}
        }}

        stage('Build & Test') {{
            steps {{
                script {{
                    env.FAILED_STAGE = 'Build & Test'
                }}
                sh 'docker build --label "org.opencontainers.image.revision=$GIT_COMMIT" -t "$APP_NAME:$IMAGE_TAG" "$APP_DIR"'
            }}
        }}

        stage('Deploy') {{
            steps {{
                script {{
                    env.FAILED_STAGE = 'Deploy'
                }}
                sh '''
                    docker rm -f "$APP_NAME" >/dev/null 2>&1 || true
                    docker run -d --name "$APP_NAME" --restart unless-stopped \
                        -p "127.0.0.1:$DEPLOY_PORT:$APP_PORT" "$APP_NAME:$IMAGE_TAG"
                '''
            }}
        }}

        stage('Smoke Test') {{
            steps {{
                script {{
                    env.FAILED_STAGE = 'Smoke Test (/health)'
                }}
                sh '''
                    for i in $(seq 1 10); do
                        if curl -fsS "http://127.0.0.1:$DEPLOY_PORT/health"; then
                            exit 0
                        fi
                        sleep 1
                    done
                    docker logs --tail 50 "$APP_NAME" || true
                    exit 1
                '''
            }}
        }}
    }}

    post {{
        always {{
            script {{
                env.BUILD_STATUS = currentBuild.currentResult ?: 'SUCCESS'
                if (fileExists('scripts/notify-telegram.sh')) {{
                    try {{
                        withCredentials([
                            string(credentialsId: 'telegram-bot-token', variable: 'TELEGRAM_BOT_TOKEN')
                        ]) {{
                            sh './scripts/notify-telegram.sh'
                        }}
                    }} catch (err) {{
                        sh './scripts/notify-telegram.sh'
                    }}
                }}
            }}
            deleteDir()
        }}
    }}
}}
"#,
        app_name = cfg.app_name,
        app_port = cfg.app_port,
        deploy_port = cfg.deploy_port,
    )
}

pub fn generate_project_files(cfg: &InitConfig, output_dir: &Path) -> Result<Vec<PathBuf>, String> {
    fs::create_dir_all(output_dir)
        .map_err(|e| format!("Gagal membuat direktori '{}': {}", output_dir.display(), e))?;

    let dockerfile_path = output_dir.join("Dockerfile");
    let jenkinsfile_path = output_dir.join("Jenkinsfile");

    fs::write(&dockerfile_path, render_dockerfile(cfg))
        .map_err(|e| format!("Gagal menulis Dockerfile: {}", e))?;
    fs::write(&jenkinsfile_path, render_jenkinsfile(cfg))
        .map_err(|e| format!("Gagal menulis Jenkinsfile: {}", e))?;

    Ok(vec![dockerfile_path, jenkinsfile_path])
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scanner::scan_directory;
    use tempfile::TempDir;

    #[test]
    fn all_stack_templates_pass_security_scanner() {
        for stack in TechStack::all() {
            let tmp = TempDir::new().unwrap();
            let cfg = InitConfig {
                app_name: "sample-service".to_string(),
                stack,
                app_port: stack.default_port(),
                deploy_port: 8081,
            };
            let created = generate_project_files(&cfg, tmp.path()).unwrap();
            assert_eq!(created.len(), 2);

            let report = scan_directory(tmp.path()).unwrap();
            assert!(
                report.is_clean(),
                "Stack {:?} failed security scan: {:?}",
                stack,
                report.violations
            );
        }
    }

    #[test]
    fn jenkinsfile_enforces_fail_closed_security_gate() {
        let cfg = InitConfig {
            app_name: "secure-app".to_string(),
            stack: TechStack::Python,
            app_port: 5000,
            deploy_port: 8081,
        };
        let content = render_jenkinsfile(&cfg);

        // Security Gate must fail-closed if scanner is missing (Default-Deny)
        assert!(content.contains("Fail-Closed / Default-Deny"));
        assert!(content.contains("exit 1"));
    }

    #[test]
    fn jenkinsfile_security_gate_uses_only_trusted_scanner() {
        let cfg = InitConfig {
            app_name: "secure-app".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        let content = render_jenkinsfile(&cfg);
        // H-1: the authoritative scanner is the admin-installed absolute path,
        // never PATH lookup and never a script shipped by the scanned repo.
        assert!(content.contains("/usr/local/bin/autore scan --path \"$APP_DIR\""));
        assert!(!content.contains("command -v autore"), "PATH lookup is repo-controllable");
        assert!(!content.contains("security-check.sh"), "repo script must not be the gate");
        assert!(!content.contains("--no-docker"), "CI must run Gitleaks + Trivy");
        assert!(content.contains("stat -c %u /usr/local/bin/autore"), "must verify root ownership");
    }
}
