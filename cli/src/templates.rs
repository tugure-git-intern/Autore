use std::fmt;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TechStack {
    Python,
    NodeJs,
    Java,
    Go,
}

impl TechStack {
    pub fn all() -> Vec<TechStack> {
        vec![
            TechStack::Python,
            TechStack::NodeJs,
            TechStack::Java,
            TechStack::Go,
        ]
    }

    pub fn from_str_loose(s: &str) -> Option<TechStack> {
        match s.trim().to_lowercase().as_str() {
            "python" | "py" => Some(TechStack::Python),
            "nodejs" | "node" | "js" | "javascript" => Some(TechStack::NodeJs),
            "java" | "spring" | "maven" => Some(TechStack::Java),
            "go" | "golang" => Some(TechStack::Go),
            _ => None,
        }
    }

    pub fn default_port(&self) -> u16 {
        match self {
            TechStack::Python => 8000,
            TechStack::NodeJs => 3000,
            TechStack::Java => 8080,
            TechStack::Go => 8080,
        }
    }
}

impl fmt::Display for TechStack {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            TechStack::Python => write!(f, "Python (3.12-slim)"),
            TechStack::NodeJs => write!(f, "Node.js (20-alpine)"),
            TechStack::Java => write!(f, "Java (Eclipse Temurin 21)"),
            TechStack::Go => write!(f, "Go (1.22-alpine multi-stage)"),
        }
    }
}

#[derive(Debug, Clone)]
pub struct InitConfig {
    pub app_name: String,
    pub stack: TechStack,
    pub app_port: u16,
    pub deploy_port: u16,
}

pub fn render_dockerfile(cfg: &InitConfig) -> String {
    match cfg.stack {
        TechStack::Python => format!(
            r#"# Generated by Autore CLI — Multi-stage Python Dockerfile (Auto-detect entrypoint)
FROM python:3.12-slim AS test
WORKDIR /app
COPY . .
RUN if [ -f requirements.txt ]; then pip install --no-cache-dir -r requirements.txt; \
    elif [ -f pyproject.toml ]; then pip install --no-cache-dir .; fi
RUN if find . -maxdepth 3 \( -name 'test_*.py' -o -name '*_test.py' \) | grep -q .; then \
        python -m unittest discover -v; \
    else \
        python -m compileall -q .; \
    fi

FROM python:3.12-slim
WORKDIR /app
COPY --from=test /usr/local /usr/local
COPY --from=test /app /app
# Tambal paket OS dari repo security. Base `python:3.12-slim` masih membawa apt
# 3.0.3, dan CVE-2026-109518 sudah punya perbaikan (3.0.4 di trixie-security),
# sehingga gerbang Trivy memblokir image. Hanya stage ini yang dikirim, jadi
# menambal di stage `test` tidak menolong. Tanpa pin versi: `upgrade` ikut
# membawa perbaikan berikutnya tanpa perlu menyunting template lagi.
RUN apt-get update \
    && apt-get -y upgrade \
    && rm -rf /var/lib/apt/lists/*
RUN useradd --system --no-create-home appuser
USER appuser
EXPOSE {port}
CMD ["sh", "-c", "if [ -f app.py ]; then exec python app.py; elif [ -f main.py ]; then exec python main.py; elif [ -f run.py ]; then exec python run.py; elif [ -f manage.py ]; then exec python manage.py runserver 0.0.0.0:{port}; else echo 'Entrypoint Python tidak ditemukan (app.py / main.py / run.py / manage.py)' >&2; exit 1; fi"]
"#,
            port = cfg.app_port
        ),
        TechStack::NodeJs => format!(
            r#"# Generated by Autore CLI — Multi-stage Node.js Dockerfile (Auto-detect entrypoint)
FROM node:20-alpine AS test
WORKDIR /app
COPY . .
RUN if [ -f package-lock.json ]; then npm ci; elif [ -f package.json ]; then npm install; fi
RUN if [ -f package.json ]; then npm run build --if-present && npm test --if-present; fi

FROM node:20-alpine
WORKDIR /app
COPY --from=test /app /app
USER node
EXPOSE {port}
CMD ["sh", "-c", "if [ -f package.json ] && node -e \"const p=require('./package.json'); process.exit(p.scripts && p.scripts.start ? 0 : 1)\"; then exec npm start; elif [ -f dist/main.js ]; then exec node dist/main.js; elif [ -f dist/index.js ]; then exec node dist/index.js; elif [ -f server.js ]; then exec node server.js; elif [ -f index.js ]; then exec node index.js; elif [ -f app.js ]; then exec node app.js; else echo 'Entrypoint Node.js tidak ditemukan (npm start / server.js / index.js / app.js)' >&2; exit 1; fi"]
"#,
            port = cfg.app_port
        ),
        TechStack::Java => format!(
            r#"# Generated by Autore CLI — Multi-stage Java 21 Dockerfile (Auto-detect Maven / Gradle)
FROM maven:3.9-eclipse-temurin-21 AS build
WORKDIR /app
COPY . .
RUN mkdir -p /out && \
    if [ -f pom.xml ]; then \
        mvn -B test package && cp target/*.jar /out/app.jar; \
    elif [ -f gradlew ]; then \
        chmod +x gradlew && ./gradlew test bootJar --no-daemon && cp build/libs/*.jar /out/app.jar; \
    else \
        echo "File pom.xml atau gradlew tidak ditemukan" >&2 && exit 1; \
    fi

FROM eclipse-temurin:21-jre-jammy
WORKDIR /app
COPY --from=build /out/app.jar /app/app.jar
RUN useradd --system --no-create-home appuser
USER appuser
EXPOSE {port}
ENTRYPOINT ["java", "-jar", "/app/app.jar"]
"#,
            port = cfg.app_port
        ),
        TechStack::Go => format!(
            r#"# Generated by Autore CLI — Multi-stage Go Dockerfile (Auto-detect module / cmd)
FROM golang:1.22-alpine AS build
WORKDIR /src
COPY . .
RUN if [ -f go.mod ]; then \
        go test ./... && \
        if [ -d ./cmd/server ]; then CGO_ENABLED=0 go build -o /out/app ./cmd/server; \
        elif [ -d ./cmd/api ]; then CGO_ENABLED=0 go build -o /out/app ./cmd/api; \
        else CGO_ENABLED=0 go build -o /out/app .; fi; \
    else \
        CGO_ENABLED=0 go build -o /out/app *.go; \
    fi

FROM alpine:3.20
WORKDIR /app
COPY --from=build /out/app /app/app
RUN adduser -D -H appuser
USER appuser
EXPOSE {port}
ENTRYPOINT ["/app/app"]
"#,
            port = cfg.app_port
        ),
    }
}

pub fn render_dockerignore() -> &'static str {
    r#"# Generated by Autore CLI — Prevent secrets & build artifacts from entering Docker image
.git
.gitignore
.env
.env.*
*.secret
*.pem
*.key
*.p12
__pycache__/
*.py[cod]
node_modules/
target/
.venv/
venv/
.superpowers/
Jenkinsfile
"#
}

pub fn render_jenkinsfile(cfg: &InitConfig) -> String {
    format!(
        r#"// Generated by Autore CLI — Standard DevSecOps Pipeline for {app_name}
// Authoritative 9-Stage Fail-Closed / Default-Deny pipeline via Trusted Shared Library.
// Security scanner (/usr/local/bin/autore, root-owned) & runtime UID != 0 check
// are enforced centrally by vars/autorePipeline.groovy on the Jenkins controller.
@Library('autore') _
autorePipeline(
    appName: '{app_name}',
    appPort: {app_port},
    deployPort: {deploy_port}
)
"#,
        app_name = cfg.app_name,
        app_port = cfg.app_port,
        deploy_port = cfg.deploy_port,
    )
}

pub const RESERVED_INFRA_PORTS: &[(u16, &str)] = &[
    (5000, "Nexus Docker Registry"),
    (8080, "Jenkins Controller"),
    (8082, "Nexus Web UI"),
    (9000, "SonarQube Server"),
];

pub fn validate_deploy_port(port: u16) -> Result<(), String> {
    if port < 1024 {
        return Err(format!(
            "Port deploy {port} terlalu rendah (gunakan port >= 1024 agar tidak butuh root)"
        ));
    }
    for (reserved, service) in RESERVED_INFRA_PORTS {
        if port == *reserved {
            return Err(format!(
                "Port {port} sudah dipakai oleh infrastruktur CI/CD ({service}). Pilih port lain (contoh: 8081, 8083, 8084)"
            ));
        }
    }
    Ok(())
}

pub fn validate_app_name(name: &str) -> Result<(), String> {
    if name.is_empty() || name.len() > 63 {
        return Err(
            "Nama aplikasi wajib diisi (1-63 karakter, huruf kecil, angka, '-', atau '_')".into(),
        );
    }
    let mut chars = name.chars();
    let first = chars.next().unwrap();
    if !first.is_ascii_lowercase() && !first.is_ascii_digit() {
        return Err("Nama aplikasi harus diawali huruf kecil (a-z) atau angka (0-9)".into());
    }
    if !chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_') {
        return Err(
            "Nama aplikasi hanya boleh berisi huruf kecil (a-z), angka (0-9), '-', atau '_'".into(),
        );
    }
    Ok(())
}

#[allow(dead_code)]
pub fn generate_project_files(cfg: &InitConfig, output_dir: &Path) -> Result<Vec<PathBuf>, String> {
    generate_project_files_with(cfg, output_dir, false)
}

pub fn generate_project_files_with(
    cfg: &InitConfig,
    output_dir: &Path,
    force: bool,
) -> Result<Vec<PathBuf>, String> {
    validate_app_name(&cfg.app_name)?;
    validate_deploy_port(cfg.deploy_port)?;
    fs::create_dir_all(output_dir)
        .map_err(|e| format!("Gagal membuat direktori '{}': {}", output_dir.display(), e))?;

    let dockerfile_path = output_dir.join("Dockerfile");
    let jenkinsfile_path = output_dir.join("Jenkinsfile");
    let dockerignore_path = output_dir.join(".dockerignore");
    let targets = [
        (&dockerfile_path, render_dockerfile(cfg)),
        (&jenkinsfile_path, render_jenkinsfile(cfg)),
        (&dockerignore_path, render_dockerignore().to_string()),
    ];

    if !force {
        for (path, _) in &targets {
            if path.exists() {
                return Err(format!(
                    "File '{}' sudah ada (gunakan --force untuk menimpa)",
                    path.display()
                ));
            }
        }
    }

    for (path, content) in &targets {
        fs::write(path, content)
            .map_err(|e| format!("Gagal menulis '{}': {}", path.display(), e))?;
    }

    Ok(vec![dockerfile_path, jenkinsfile_path, dockerignore_path])
}

/// Kode contoh minimal yang langsung bisa dibuka (endpoint `/` + `/health`).
/// Isinya sama dengan yang dipakai sandbox, jadi satu sumber kebenaran.
pub const CONTOH_APP_PY: &str = include_str!("../../sandbox/dummy-app/app.py");
pub const CONTOH_TEST_PY: &str = include_str!("../../sandbox/dummy-app/test_app.py");

/// Tulis kode contoh ke folder project supaya tahap deploy tidak ditolak karena
/// folder kosong. File yang sudah ada TIDAK ditimpa.
///
/// ponytail: hanya stack yang punya contoh (python). Tambah cabang kalau ada
/// template stack lain yang siap dipakai.
pub fn tulis_kode_contoh(dir: &Path, stack: TechStack) -> std::io::Result<Vec<&'static str>> {
    let mut dibuat = Vec::new();
    if stack == TechStack::Python {
        for (nama, isi) in [("app.py", CONTOH_APP_PY), ("test_app.py", CONTOH_TEST_PY)] {
            let tujuan = dir.join(nama);
            if !tujuan.exists() {
                fs::create_dir_all(dir)?;
                fs::write(&tujuan, isi)?;
                dibuat.push(nama);
            }
        }
    }
    Ok(dibuat)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scanner::scan_directory;
    use tempfile::TempDir;

    #[test]
    fn kode_contoh_ditulis_sekali_dan_tidak_menimpa() {
        let tmp = TempDir::new().unwrap();
        let dir = tmp.path();
        let dibuat = tulis_kode_contoh(dir, TechStack::Python).unwrap();
        assert_eq!(dibuat, vec!["app.py", "test_app.py"]);
        assert!(fs::read_to_string(dir.join("app.py")).unwrap().contains("8000"));

        fs::write(dir.join("app.py"), "punya saya").unwrap();
        let lagi = tulis_kode_contoh(dir, TechStack::Python).unwrap();
        assert!(lagi.is_empty(), "file yang sudah ada tidak boleh ditimpa");
        assert_eq!(fs::read_to_string(dir.join("app.py")).unwrap(), "punya saya");
    }

    #[test]
    fn kode_contoh_membuat_folder_yang_belum_ada() {
        let tmp = TempDir::new().unwrap();
        let belum = tmp.path().join("belum-ada");
        let dibuat = tulis_kode_contoh(&belum, TechStack::Python).unwrap();
        assert_eq!(dibuat.len(), 2);
        assert!(belum.join("app.py").exists());
    }

    #[test]
    fn kode_contoh_kosong_untuk_stack_tanpa_template() {
        let tmp = TempDir::new().unwrap();
        assert!(tulis_kode_contoh(tmp.path(), TechStack::Go).unwrap().is_empty());
    }

    #[test]
    fn dockerfile_python_menambal_paket_os_di_stage_runtime() {
        let cfg = InitConfig {
            app_name: "sample-service".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        let dockerfile = render_dockerfile(&cfg);

        // Tarikan terakhir adalah stage yang dikirim: menambal paket OS di stage
        // `test` tidak menolong image yang dipindai Trivy, karena stage runtime
        // memulai lagi dari base yang sama (kasus nyata: apt 3.0.3 → 3.0.4).
        let stage_runtime = dockerfile
            .rfind("FROM python:3.12-slim")
            .expect("stage runtime ada");
        let tambalan = dockerfile
            .find("apt-get -y upgrade")
            .expect("paket OS ditambal di image akhir");
        assert!(
            tambalan > stage_runtime,
            "tambalan harus di stage runtime, bukan stage test"
        );
        // `apt-get upgrade` butuh root, jadi harus mendahului `USER appuser`.
        let jadi_non_root = dockerfile.find("USER appuser").expect("USER non-root ada");
        assert!(
            tambalan < jadi_non_root,
            "tambalan harus jalan sebagai root sebelum USER appuser"
        );
        assert!(
            dockerfile.contains("rm -rf /var/lib/apt/lists/*"),
            "daftar paket apt wajib dibersihkan supaya image tidak membengkak"
        );
    }

    #[test]
    fn all_stack_templates_pass_security_scanner() {
        for stack in TechStack::all() {
            let tmp = TempDir::new().unwrap();
            let cfg = InitConfig {
                app_name: "sample-service".to_string(),
                stack,
                app_port: stack.default_port(),
                deploy_port: 8081,
            };
            let created = generate_project_files(&cfg, tmp.path()).unwrap();
            assert_eq!(created.len(), 3);

            let report = scan_directory(tmp.path()).unwrap();
            assert!(
                report.is_clean(),
                "Stack {:?} failed security scan: {:?}",
                stack,
                report.violations
            );
        }
    }

    #[test]
    fn rejects_invalid_or_injection_app_names() {
        for bad in [
            "",
            "bad'name",
            "vuln'; echo pwned; echo '",
            "UpperCase",
            "-leading",
            "with space",
            "../escape",
            "a/b",
        ] {
            assert!(
                validate_app_name(bad).is_err(),
                "Invalid app_name {bad:?} was accepted"
            );
        }
        for good in ["my-tugure-app", "service_1", "autore-dummy"] {
            assert!(validate_app_name(good).is_ok(), "{good:?} rejected");
        }
    }

    #[test]
    fn rejects_reserved_infra_and_privileged_deploy_ports() {
        for bad in [80, 443, 1023, 5000, 8080, 8082, 9000] {
            assert!(
                validate_deploy_port(bad).is_err(),
                "Reserved/privileged port {bad} should be rejected"
            );
        }
        for good in [8081, 8083, 8084, 3000, 8000] {
            assert!(
                validate_deploy_port(good).is_ok(),
                "Valid deploy port {good} rejected"
            );
        }
    }

    #[test]
    fn refuses_to_overwrite_existing_files_without_force() {
        let tmp = TempDir::new().unwrap();
        let cfg = InitConfig {
            app_name: "sample-service".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        generate_project_files(&cfg, tmp.path()).unwrap();
        fs::write(tmp.path().join("Dockerfile"), "# custom\n").unwrap();

        assert!(
            generate_project_files(&cfg, tmp.path()).is_err(),
            "clobbered existing Dockerfile without --force"
        );
        assert_eq!(
            fs::read_to_string(tmp.path().join("Dockerfile")).unwrap(),
            "# custom\n"
        );

        generate_project_files_with(&cfg, tmp.path(), true).unwrap();
        assert!(fs::read_to_string(tmp.path().join("Dockerfile"))
            .unwrap()
            .contains("FROM python:3.12-slim"));
    }

    #[test]
    fn generates_dockerignore_excluding_secrets_and_git() {
        let tmp = TempDir::new().unwrap();
        let cfg = InitConfig {
            app_name: "sample-service".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        generate_project_files(&cfg, tmp.path()).unwrap();
        let ignore = fs::read_to_string(tmp.path().join(".dockerignore")).unwrap();
        for pattern in [".git", ".env", "*.secret", "*.key", "Jenkinsfile"] {
            assert!(
                ignore.contains(pattern),
                "missing {pattern} in .dockerignore"
            );
        }
    }

    #[test]
    fn python_template_copies_installed_packages_into_runtime_stage() {
        let cfg = InitConfig {
            app_name: "sample-service".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        let df = render_dockerfile(&cfg);
        assert!(
            df.contains("COPY --from=test /usr/local /usr/local"),
            "runtime stage loses pip-installed dependencies:\n{df}"
        );
        assert!(
            df.contains("main.py") && df.contains("manage.py"),
            "missing Python entrypoint auto-detect:\n{df}"
        );
    }

    #[test]
    fn templates_auto_detect_common_entrypoints_and_build_tools() {
        let node_df = render_dockerfile(&InitConfig {
            app_name: "node-svc".to_string(),
            stack: TechStack::NodeJs,
            app_port: 3000,
            deploy_port: 8081,
        });
        assert!(
            node_df.contains("npm start")
                && node_df.contains("server.js")
                && node_df.contains("dist/main.js")
        );

        let java_df = render_dockerfile(&InitConfig {
            app_name: "java-svc".to_string(),
            stack: TechStack::Java,
            app_port: 8080,
            deploy_port: 8081,
        });
        assert!(java_df.contains("pom.xml") && java_df.contains("gradlew"));
    }

    #[test]
    fn jenkinsfile_enforces_fail_closed_security_gate() {
        let cfg = InitConfig {
            app_name: "secure-app".to_string(),
            stack: TechStack::Python,
            app_port: 5000,
            deploy_port: 8081,
        };
        let content = render_jenkinsfile(&cfg);

        // Enforces authoritative Trusted Shared Library (Fail-Closed / Default-Deny)
        assert!(content.contains("@Library('autore') _"));
        assert!(content.contains("autorePipeline("));
        assert!(content.contains("appName: 'secure-app'"));
        assert!(content.contains("appPort: 5000"));
        assert!(content.contains("deployPort: 8081"));
    }

    #[test]
    fn jenkinsfile_security_gate_uses_only_trusted_scanner() {
        let cfg = InitConfig {
            app_name: "secure-app".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        let content = render_jenkinsfile(&cfg);
        // C-2 & H-1: Repo Jenkinsfile delegates to @Library('autore') _ and never
        // executes repo-controlled scripts or --no-docker flags.
        assert!(content.contains("@Library('autore') _"));
        assert!(
            !content.contains("command -v autore"),
            "PATH lookup is repo-controllable"
        );
        assert!(
            !content.contains("security-check.sh"),
            "repo script must not be the gate"
        );
        assert!(
            !content.contains("--no-docker"),
            "CI must run Gitleaks + Trivy"
        );
    }
}
