    #[test]
    fn dockerfile_java_jalan_tanpa_maven_atau_gradle() {
        let cfg = InitConfig {
            app_name: "java-svc".to_string(),
            stack: TechStack::Java,
            app_port: 8080,
            deploy_port: 8081,
        };
        let df = render_dockerfile(&cfg);

        // Project Java yang cuma punya satu berkas (tanpa pom.xml/gradlew) harus tetap
        // bisa dibangun: kasus nyata tes-java #1 mati di `docker build` step 4 karena
        // tidak ada pom.xml, padahal Dockerfile ada.
        let cabang_pom = df.find("[ -f pom.xml ]").expect("cabang Maven ada");
        let cabang_gradle = df.find("[ -f gradlew ]").expect("cabang Gradle ada");
        let cabang_polos = df.find("[ -f Main.java ]").expect("cabang JDK polos ada");
        assert!(
            cabang_pom < cabang_gradle && cabang_gradle < cabang_polos,
            "project Maven/Gradle nyata tidak boleh keburu diambil cabang JDK polos:\n{df}"
        );
        assert!(
            df.contains("javac -d /out Main.java"),
            "tanpa javac, folder berisi Main.java saja tidak bisa jadi image:\n{df}"
        );
        // Pesan error wajib menyebut ketiga jalur supaya orang tahu apa yang kurang.
        for jalur in ["pom.xml", "gradlew", "Main.java"] {
            assert!(df.contains(jalur), "percabangan/pesan tidak menyebut {jalur}");
        }
        assert!(
            df.contains("java -cp /app Main"),
            "runtime harus bisa menjalankan kelas hasil javac:\n{df}"
        );
    }

    #[test]
    fn dockerfile_java_menambal_paket_os_sebelum_jadi_non_root() {
        let cfg = InitConfig {
            app_name: "java-svc".to_string(),
            stack: TechStack::Java,
            app_port: 8080,
            deploy_port: 8081,
        };
        let df = render_dockerfile(&cfg);

        // Terukur: tanpa tambalan, image runtime (eclipse-temurin:21-jre-jammy) punya
        // 2 CVE HIGH dari paket apt. Hanya stage terakhir yang dipindai Trivy, jadi
        // tambalan harus ada di stage runtime dan jalan sebagai root.
        let stage_runtime = df
            .rfind("FROM eclipse-temurin:21-jre-jammy")
            .expect("stage runtime Java ada");
        let tambalan = df.find("apt-get -y upgrade").expect("paket OS ditambal");
        assert!(
            tambalan > stage_runtime,
            "tambalan harus di stage runtime, bukan stage build"
        );
        let jadi_non_root = df.find("USER appuser").expect("USER non-root ada");
        assert!(
            tambalan < jadi_non_root,
            "apt-get upgrade butuh root: harus sebelum USER appuser"
        );
        assert!(df.contains("rm -rf /var/lib/apt/lists/*"));
    }

    #[test]
    fn dockerfile_go_pakai_toolchain_dan_runtime_yang_bebas_cve() {
        let cfg = InitConfig {
            app_name: "go-svc".to_string(),
            stack: TechStack::Go,
            app_port: 8080,
            deploy_port: 8081,
        };
        let df = render_dockerfile(&cfg);

        // Terukur: golang 1.22 (stdlib v1.22.12) = 26 CVE HIGH/CRITICAL di hasil pindai
        // `gobinary`, termasuk CVE-2025-68121 CRITICAL; perbaikan CVE-2025-68121 &
        // CVE-2026-111943 baru ada di 1.27.x. Jangan turunkan plafon ini.
        let toolchain = df
            .lines()
            .find(|l| l.starts_with("FROM golang:"))
            .expect("base build Go ada");
        let minor: u32 = toolchain
            .trim_start_matches("FROM golang:1.")
            .split(|c: char| !c.is_ascii_digit())
            .next()
            .and_then(|v| v.parse().ok())
            .expect("tag minor golang terbaca");
        assert!(minor >= 27, "stdlib golang terlalu tua: {toolchain}");

        // alpine 3.20 sudah EOL (Trivy: "security updates are not provided"); 3.21
        // terukur bersih untuk paket OS-nya.
        let runtime = df
            .lines()
            .filter(|l| l.starts_with("FROM alpine:"))
            .next_back()
            .expect("runtime Go ada");
        let minor_runtime: u32 = runtime
            .trim_start_matches("FROM alpine:3.")
            .split(|c: char| !c.is_ascii_digit())
            .next()
            .and_then(|v| v.parse().ok())
            .expect("tag minor alpine terbaca");
        assert!(minor_runtime >= 21, "runtime alpine sudah EOL: {runtime}");
    }
