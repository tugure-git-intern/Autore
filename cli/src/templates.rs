use std::fmt;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TechStack {
    Python,
    NodeJs,
    Java,
    Go,
}

impl TechStack {
    pub fn all() -> Vec<TechStack> {
        vec![
            TechStack::Python,
            TechStack::NodeJs,
            TechStack::Java,
            TechStack::Go,
        ]
    }

    pub fn from_str_loose(s: &str) -> Option<TechStack> {
        match s.trim().to_lowercase().as_str() {
            "python" | "py" => Some(TechStack::Python),
            "nodejs" | "node" | "js" | "javascript" => Some(TechStack::NodeJs),
            "java" | "spring" | "maven" => Some(TechStack::Java),
            "go" | "golang" => Some(TechStack::Go),
            _ => None,
        }
    }

    pub fn default_port(&self) -> u16 {
        match self {
            TechStack::Python => 8000,
            TechStack::NodeJs => 3000,
            TechStack::Java => 8080,
            TechStack::Go => 8080,
        }
    }
}

impl fmt::Display for TechStack {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            TechStack::Python => write!(f, "Python (3.12-slim)"),
            TechStack::NodeJs => write!(f, "Node.js (20-alpine)"),
            TechStack::Java => write!(f, "Java (Eclipse Temurin 21)"),
            TechStack::Go => write!(f, "Go (1.22-alpine multi-stage)"),
        }
    }
}

#[derive(Debug, Clone)]
pub struct InitConfig {
    pub app_name: String,
    pub stack: TechStack,
    pub app_port: u16,
    pub deploy_port: u16,
}

pub fn render_dockerfile(cfg: &InitConfig) -> String {
    match cfg.stack {
        TechStack::Python => format!(
            r#"# Generated by Autore CLI — Multi-stage Python Dockerfile
FROM python:3.12-slim AS test
WORKDIR /app
COPY . .
RUN if [ -f requirements.txt ]; then pip install --no-cache-dir -r requirements.txt; fi
RUN if find . -maxdepth 3 \( -name 'test_*.py' -o -name '*_test.py' \) | grep -q .; then \
        python -m unittest discover -v; \
    else \
        python -m compileall -q .; \
    fi

FROM python:3.12-slim
WORKDIR /app
COPY --from=test /usr/local /usr/local
COPY --from=test /app /app
RUN useradd --system --no-create-home appuser
USER appuser
EXPOSE {port}
CMD ["python", "app.py"]
"#,
            port = cfg.app_port
        ),
        TechStack::NodeJs => format!(
            r#"# Generated by Autore CLI — Multi-stage Node.js Dockerfile
FROM node:20-alpine AS test
WORKDIR /app
COPY . .
RUN if [ -f package-lock.json ]; then npm ci; elif [ -f package.json ]; then npm install; fi
RUN if [ -f package.json ]; then npm test --if-present; fi

FROM node:20-alpine
WORKDIR /app
COPY --from=test /app /app
USER node
EXPOSE {port}
CMD ["node", "index.js"]
"#,
            port = cfg.app_port
        ),
        TechStack::Java => format!(
            r#"# Generated by Autore CLI — Multi-stage Java 21 Dockerfile
FROM maven:3.9-eclipse-temurin-21 AS build
WORKDIR /app
COPY pom.xml .
COPY src ./src
RUN mvn -B test package

FROM eclipse-temurin:21-jre-jammy
WORKDIR /app
COPY --from=build /app/target/*.jar /app/app.jar
RUN useradd --system --no-create-home appuser
USER appuser
EXPOSE {port}
ENTRYPOINT ["java", "-jar", "/app/app.jar"]
"#,
            port = cfg.app_port
        ),
        TechStack::Go => format!(
            r#"# Generated by Autore CLI — Multi-stage Go Dockerfile
FROM golang:1.22-alpine AS build
WORKDIR /src
COPY . .
RUN if [ -f go.mod ]; then go test ./... && CGO_ENABLED=0 go build -o /out/app .; else CGO_ENABLED=0 go build -o /out/app *.go; fi

FROM alpine:3.20
WORKDIR /app
COPY --from=build /out/app /app/app
RUN adduser -D -H appuser
USER appuser
EXPOSE {port}
ENTRYPOINT ["/app/app"]
"#,
            port = cfg.app_port
        ),
    }
}

pub fn render_dockerignore() -> &'static str {
    r#"# Generated by Autore CLI — Prevent secrets & build artifacts from entering Docker image
.git
.gitignore
.env
.env.*
*.secret
*.pem
*.key
*.p12
__pycache__/
*.py[cod]
node_modules/
target/
.venv/
venv/
.superpowers/
Jenkinsfile
"#
}

pub fn render_jenkinsfile(cfg: &InitConfig) -> String {
    format!(
        r#"// Generated by Autore CLI — Standard DevSecOps Pipeline for {app_name}
// Authoritative 9-Stage Fail-Closed / Default-Deny pipeline via Trusted Shared Library.
// Security scanner (/usr/local/bin/autore, root-owned) & runtime UID != 0 check
// are enforced centrally by vars/autorePipeline.groovy on the Jenkins controller.
@Library('autore') _
autorePipeline(
    appName: '{app_name}',
    appPort: {app_port},
    deployPort: {deploy_port}
)
"#,
        app_name = cfg.app_name,
        app_port = cfg.app_port,
        deploy_port = cfg.deploy_port,
    )
}

pub fn validate_app_name(name: &str) -> Result<(), String> {
    if name.is_empty() || name.len() > 63 {
        return Err(
            "Nama aplikasi wajib diisi (1-63 karakter, huruf kecil, angka, '-', atau '_')".into(),
        );
    }
    let mut chars = name.chars();
    let first = chars.next().unwrap();
    if !first.is_ascii_lowercase() && !first.is_ascii_digit() {
        return Err(
            "Nama aplikasi harus diawali huruf kecil (a-z) atau angka (0-9)".into(),
        );
    }
    if !chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_') {
        return Err(
            "Nama aplikasi hanya boleh berisi huruf kecil (a-z), angka (0-9), '-', atau '_'".into(),
        );
    }
    Ok(())
}

#[allow(dead_code)]
pub fn generate_project_files(cfg: &InitConfig, output_dir: &Path) -> Result<Vec<PathBuf>, String> {
    generate_project_files_with(cfg, output_dir, false)
}

pub fn generate_project_files_with(
    cfg: &InitConfig,
    output_dir: &Path,
    force: bool,
) -> Result<Vec<PathBuf>, String> {
    validate_app_name(&cfg.app_name)?;
    fs::create_dir_all(output_dir)
        .map_err(|e| format!("Gagal membuat direktori '{}': {}", output_dir.display(), e))?;

    let dockerfile_path = output_dir.join("Dockerfile");
    let jenkinsfile_path = output_dir.join("Jenkinsfile");
    let dockerignore_path = output_dir.join(".dockerignore");
    let targets = [
        (&dockerfile_path, render_dockerfile(cfg)),
        (&jenkinsfile_path, render_jenkinsfile(cfg)),
        (&dockerignore_path, render_dockerignore().to_string()),
    ];

    if !force {
        for (path, _) in &targets {
            if path.exists() {
                return Err(format!(
                    "File '{}' sudah ada (gunakan --force untuk menimpa)",
                    path.display()
                ));
            }
        }
    }

    for (path, content) in &targets {
        fs::write(path, content)
            .map_err(|e| format!("Gagal menulis '{}': {}", path.display(), e))?;
    }

    Ok(vec![dockerfile_path, jenkinsfile_path, dockerignore_path])
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scanner::scan_directory;
    use tempfile::TempDir;

    #[test]
    fn all_stack_templates_pass_security_scanner() {
        for stack in TechStack::all() {
            let tmp = TempDir::new().unwrap();
            let cfg = InitConfig {
                app_name: "sample-service".to_string(),
                stack,
                app_port: stack.default_port(),
                deploy_port: 8081,
            };
            let created = generate_project_files(&cfg, tmp.path()).unwrap();
            assert_eq!(created.len(), 3);

            let report = scan_directory(tmp.path()).unwrap();
            assert!(
                report.is_clean(),
                "Stack {:?} failed security scan: {:?}",
                stack,
                report.violations
            );
        }
    }

    #[test]
    fn rejects_invalid_or_injection_app_names() {
        for bad in [
            "",
            "bad'name",
            "vuln'; echo pwned; echo '",
            "UpperCase",
            "-leading",
            "with space",
            "../escape",
            "a/b",
        ] {
            assert!(
                validate_app_name(bad).is_err(),
                "Invalid app_name {bad:?} was accepted"
            );
        }
        for good in ["my-tugure-app", "service_1", "autore-dummy"] {
            assert!(validate_app_name(good).is_ok(), "{good:?} rejected");
        }
    }

    #[test]
    fn refuses_to_overwrite_existing_files_without_force() {
        let tmp = TempDir::new().unwrap();
        let cfg = InitConfig {
            app_name: "sample-service".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        generate_project_files(&cfg, tmp.path()).unwrap();
        fs::write(tmp.path().join("Dockerfile"), "# custom\n").unwrap();

        assert!(
            generate_project_files(&cfg, tmp.path()).is_err(),
            "clobbered existing Dockerfile without --force"
        );
        assert_eq!(
            fs::read_to_string(tmp.path().join("Dockerfile")).unwrap(),
            "# custom\n"
        );

        generate_project_files_with(&cfg, tmp.path(), true).unwrap();
        assert!(fs::read_to_string(tmp.path().join("Dockerfile"))
            .unwrap()
            .contains("FROM python:3.12-slim"));
    }

    #[test]
    fn generates_dockerignore_excluding_secrets_and_git() {
        let tmp = TempDir::new().unwrap();
        let cfg = InitConfig {
            app_name: "sample-service".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        generate_project_files(&cfg, tmp.path()).unwrap();
        let ignore = fs::read_to_string(tmp.path().join(".dockerignore")).unwrap();
        for pattern in [".git", ".env", "*.secret", "*.key", "Jenkinsfile"] {
            assert!(ignore.contains(pattern), "missing {pattern} in .dockerignore");
        }
    }

    #[test]
    fn python_template_copies_installed_packages_into_runtime_stage() {
        let cfg = InitConfig {
            app_name: "sample-service".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        let df = render_dockerfile(&cfg);
        assert!(
            df.contains("COPY --from=test /usr/local /usr/local"),
            "runtime stage loses pip-installed dependencies:\n{df}"
        );
    }

    #[test]
    fn jenkinsfile_enforces_fail_closed_security_gate() {
        let cfg = InitConfig {
            app_name: "secure-app".to_string(),
            stack: TechStack::Python,
            app_port: 5000,
            deploy_port: 8081,
        };
        let content = render_jenkinsfile(&cfg);

        // Enforces authoritative Trusted Shared Library (Fail-Closed / Default-Deny)
        assert!(content.contains("@Library('autore') _"));
        assert!(content.contains("autorePipeline("));
        assert!(content.contains("appName: 'secure-app'"));
        assert!(content.contains("appPort: 5000"));
        assert!(content.contains("deployPort: 8081"));
    }

    #[test]
    fn jenkinsfile_security_gate_uses_only_trusted_scanner() {
        let cfg = InitConfig {
            app_name: "secure-app".to_string(),
            stack: TechStack::Python,
            app_port: 8000,
            deploy_port: 8081,
        };
        let content = render_jenkinsfile(&cfg);
        // C-2 & H-1: Repo Jenkinsfile delegates to @Library('autore') _ and never
        // executes repo-controlled scripts or --no-docker flags.
        assert!(content.contains("@Library('autore') _"));
        assert!(!content.contains("command -v autore"), "PATH lookup is repo-controllable");
        assert!(!content.contains("security-check.sh"), "repo script must not be the gate");
        assert!(!content.contains("--no-docker"), "CI must run Gitleaks + Trivy");
    }
}
