pub fn render_jenkinsfile(cfg: &InitConfig) -> String {
    format!(
        r#"// Generated by Autore CLI — Standard DevSecOps Pipeline for {app_name}
// Authoritative 9-Stage Fail-Closed / Default-Deny pipeline via Trusted Shared Library.
// Security scanner (/usr/local/bin/autore, root-owned) & runtime UID != 0 check
// are enforced centrally by vars/autorePipeline.groovy on the Jenkins controller.
@Library('autore') _
autorePipeline(
    appName: '{app_name}',
    appPort: {app_port},
    deployPort: {deploy_port}
)
"#,
        app_name = cfg.app_name,
        app_port = cfg.app_port,
        deploy_port = cfg.deploy_port,
    )
}

pub const RESERVED_INFRA_PORTS: &[(u16, &str)] = &[
    (5000, "Nexus Docker Registry"),
    (8080, "Jenkins Controller"),
    (8082, "Nexus Web UI"),
    (9000, "SonarQube Server"),
];

pub fn validate_deploy_port(port: u16) -> Result<(), String> {
    if port < 1024 {
        return Err(format!(
            "Port deploy {port} terlalu rendah (gunakan port >= 1024 agar tidak butuh root)"
        ));
    }
    for (reserved, service) in RESERVED_INFRA_PORTS {
        if port == *reserved {
            return Err(format!(
                "Port {port} sudah dipakai oleh infrastruktur CI/CD ({service}). Pilih port lain (contoh: 8081, 8083, 8084)"
            ));
        }
    }
    Ok(())
}

pub fn validate_app_name(name: &str) -> Result<(), String> {
    if name.is_empty() || name.len() > 63 {
        return Err(
            "Nama aplikasi wajib diisi (1-63 karakter, huruf kecil, angka, '-', atau '_')".into(),
        );
    }
    let mut chars = name.chars();
    let first = chars.next().unwrap();
    if !first.is_ascii_lowercase() && !first.is_ascii_digit() {
        return Err("Nama aplikasi harus diawali huruf kecil (a-z) atau angka (0-9)".into());
    }
    if !chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_') {
        return Err(
            "Nama aplikasi hanya boleh berisi huruf kecil (a-z), angka (0-9), '-', atau '_'".into(),
        );
    }
    Ok(())
}

#[allow(dead_code)]
pub fn generate_project_files(cfg: &InitConfig, output_dir: &Path) -> Result<Vec<PathBuf>, String> {
    generate_project_files_with(cfg, output_dir, false)
}

pub fn generate_project_files_with(
    cfg: &InitConfig,
    output_dir: &Path,
    force: bool,
) -> Result<Vec<PathBuf>, String> {
    validate_app_name(&cfg.app_name)?;
    validate_deploy_port(cfg.deploy_port)?;
    fs::create_dir_all(output_dir)
        .map_err(|e| format!("Gagal membuat direktori '{}': {}", output_dir.display(), e))?;

    let dockerfile_path = output_dir.join("Dockerfile");
    let jenkinsfile_path = output_dir.join("Jenkinsfile");
    let dockerignore_path = output_dir.join(".dockerignore");
    let targets = [
        (&dockerfile_path, render_dockerfile(cfg)),
        (&jenkinsfile_path, render_jenkinsfile(cfg)),
        (&dockerignore_path, render_dockerignore().to_string()),
    ];

    if !force {
        for (path, _) in &targets {
            if path.exists() {
                return Err(format!(
                    "File '{}' sudah ada (gunakan --force untuk menimpa)",
                    path.display()
                ));
            }
        }
    }

    for (path, content) in &targets {
        fs::write(path, content)
            .map_err(|e| format!("Gagal menulis '{}': {}", path.display(), e))?;
    }

    Ok(vec![dockerfile_path, jenkinsfile_path, dockerignore_path])
}

/// Kode contoh minimal yang langsung bisa dibuka (endpoint `/` + `/health`).
/// Isinya sama dengan yang dipakai sandbox, jadi satu sumber kebenaran.
pub const CONTOH_APP_PY: &str = include_str!("../../sandbox/dummy-app/app.py");
pub const CONTOH_TEST_PY: &str = include_str!("../../sandbox/dummy-app/test_app.py");

/// Contoh Node.js juga datang dari sandbox supaya tidak ada dua versi contoh.
/// `package.json`-nya memakai `npm start` + `npm test` (`node --test`), jadi
/// Dockerfile hasil generate langsung menemukan entrypoint dan menjalankan tes.
pub const CONTOH_PACKAGE_JSON: &str = include_str!("../../sandbox/dummy-app-node/package.json");
pub const CONTOH_APP_JS: &str = include_str!("../../sandbox/dummy-app-node/app.js");
pub const CONTOH_TEST_JS: &str = include_str!("../../sandbox/dummy-app-node/test.js");

/// Contoh Java: satu berkas, tanpa Maven/Gradle, langsung menjawab `/` & `/health`.
/// Dockerfile hasil generate punya cabang `Main.java` khusus untuk bentuk ini.
pub const CONTOH_MAIN_JAVA: &str = include_str!("../../sandbox/dummy-app-java/Main.java");

/// Contoh Go: `go.mod` bikin Dockerfile memakai cabang `go test ./...` + `go build .`,
/// jadi tesnya benar-benar jalan sebelum image jadi.
pub const CONTOH_GO_MOD: &str = include_str!("../../sandbox/dummy-app-go/go.mod");
pub const CONTOH_MAIN_GO: &str = include_str!("../../sandbox/dummy-app-go/main.go");
pub const CONTOH_MAIN_TEST_GO: &str = include_str!("../../sandbox/dummy-app-go/main_test.go");

/// Berkas contoh per stack. Semua stack punya contoh yang langsung jalan (endpoint
/// `/` + `/health` di port bawaan stack); tanpa itu, `--kode contoh` menulis folder
/// kosong dan tahap deploy selalu ditolak.
fn berkas_contoh(stack: TechStack) -> &'static [(&'static str, &'static str)] {
    match stack {
        TechStack::Python => &[("app.py", CONTOH_APP_PY), ("test_app.py", CONTOH_TEST_PY)],
        TechStack::NodeJs => &[
            ("package.json", CONTOH_PACKAGE_JSON),
            ("app.js", CONTOH_APP_JS),
            ("test.js", CONTOH_TEST_JS),
        ],
        TechStack::Java => &[("Main.java", CONTOH_MAIN_JAVA)],
        TechStack::Go => &[
            ("go.mod", CONTOH_GO_MOD),
            ("main.go", CONTOH_MAIN_GO),
            ("main_test.go", CONTOH_MAIN_TEST_GO),
        ],
    }
}

/// Tulis kode contoh ke folder project supaya tahap deploy tidak ditolak karena
/// folder kosong. File yang sudah ada TIDAK ditimpa.
pub fn tulis_kode_contoh(dir: &Path, stack: TechStack) -> std::io::Result<Vec<&'static str>> {
    let mut dibuat = Vec::new();
    for (nama, isi) in berkas_contoh(stack) {
        let tujuan = dir.join(nama);
        if tujuan.exists() {
            continue;
        }
        fs::create_dir_all(dir)?;
        fs::write(&tujuan, isi)?;
        dibuat.push(*nama);
    }
    Ok(dibuat)
}

